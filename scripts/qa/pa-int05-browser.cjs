const stableError = { error: { codigo: 'RESULTADO_NO_DETERMINADO', mensaje: 'Lectura temporalmente no disponible.', campos: [], ambitos: [], reintento: 'NO_APLICA' }, comando_id: null, resultado_concluyente: false }
function sqlProjection() {
  const socket = process.env.PA_QA_SOCKET, psql = process.env.PA_QA_PSQL
  assert(/^\/private\/tmp\/pa-int03a-[a-z0-9_]+\/socket$/.test(socket || ''), 'Socket exclusivo del fixture sintético requerido')
  assert(psql && psql.endsWith('/psql'))
  const value = execFileSync(psql, ['-X', '-qAt', '-v', 'ON_ERROR_STOP=1', '-h', socket, '-p', '55435', '-U', 'postgres', '-d', 'pa_int03a_ensayo'], {
    input: "BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY; SET LOCAL statement_timeout='10s'; SELECT public.pa_impacto_leer(); COMMIT;",
    encoding: 'utf8', timeout: 15000, env: Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith('PG'))),
  }).trim()
  return JSON.parse(value).data
}
